// 界面三处读它（凭证弹窗 / 插件详情页 / 节点与 agent 工具的「使用说明」）。

const usageDoc = "# Elasticsearch\n\n" +
	"把 ES 接进工作流：查日志与文档、灌数据、管索引。**ES 7/8/9 与 OpenSearch 都支持**——\n" +
	"插件走标准 REST 接口，不锁客户端版本。\n\n" +
	"## 配凭证\n\n" +
	"| 字段 | 怎么填 |\n" +
	"|---|---|\n" +
	"| 地址 | 集群地址带协议与端口，如 `https://es.internal:9200`。多节点填其中一个即可 |\n" +
	"| 用户名 / 密码 | basic 认证（ES 8 默认账号是 `elastic`）|\n" +
	"| API Key | Kibana → Stack Management → **API Keys** 生成的 encoded 值。填了它就不用用户名密码，**更推荐**：能按索引限权、能单独吊销 |\n" +
	"| 跳过证书校验 | 自建集群用自签证书时选 `on`（连接仍加密，但不校验对端身份）|\n\n" +
	"配好点「检查凭证」：通了会显示发行版、版本、集群名与集群状态。\n\n" +
	"## 挑哪个操作\n\n" +
	"- **查东西** → 搜索。两种写法二选一：**查询**收 ES Query DSL 原文\n" +
	"  （照官方文档写，`{\"bool\":{\"must\":[…]}}`），**简式查询**收 Lucene 一行式\n" +
	"  （`status:error AND host:a1`，试探性查询最快）。排序填 `@timestamp:desc`。\n" +
	"- **只要个数** → 统计条数。它的数是**精确的**，搜索的总数不一定（见下）。\n" +
	"- **按 ID 存取** → 取文档 / 写入文档 / 更新文档 / 删除文档。\n" +
	"  更新是局部改（只动给出的字段），写入是整篇覆盖。\n" +
	"- **灌一批数据** → 批量写入，一个请求写多篇，比逐条快一个量级。\n" +
	"- **算分布/趋势** → 搜索里填**聚合**（`{\"by_host\":{\"terms\":{\"field\":\"host.keyword\"}}}`），\n" +
	"  取几条留空就只回聚合结果不回文档。\n" +
	"- **管索引** → 索引列表 / 建索引 / 删索引 / 看字段定义 / 加字段定义 / 切别名 / 重建索引。\n" +
	"- **上面没有的接口** → 通用调用（`_tasks`、`_ilm`、`_snapshot`、`_sql`…）。\n\n" +
	"## 幂等：别把重跑写成重复数据\n\n" +
	"工作流会重试、会被重复触发。**拿业务主键当文档 ID**，重跑就是覆盖同一篇而不是写出第二篇：\n" +
	"写入文档填「文档 ID」，批量写入填「拿哪个字段当 ID」。不给 ID 时 ES 每次都生成新的，\n" +
	"同一批数据跑两遍就有两份。\n\n" +
	"## 坑\n\n" +
	"- **搜索的「命中总数」默认只精确到 10000**：超出时 ES 回的是下界，出参里的\n" +
	"  `总数是下界` 会是 true。要准确总数就打开「精确总数」（更慢），或者用「统计条数」。\n" +
	"- **写完不是立刻能搜到**：ES 默认约 1 秒后才刷新可见。写完马上查却查不到多半是这个。\n" +
	"  单条要立刻可见就开「立即可搜」，但**别在批量循环里开**——每次都强制刷新分片，很慢。\n" +
	"- **已有字段的类型改不了**：这是 ES 的硬限制。改类型的唯一路径是\n" +
	"  建新索引（新 mapping）→ 重建索引 → 切别名，三个操作都在这儿。\n" +
	"  查询方一直用别名就完全无感知。\n" +
	"- **`text` 字段不能直接聚合/排序**，要用它的 `.keyword` 子字段\n" +
	"  （`host` → `host.keyword`）。「看字段定义」能确认索引里到底是什么类型。\n" +
	"- **危险操作有闸**：按查询删除必须给查询（不给等于删光索引）；删索引不接受 `*` 和 `_all`\n" +
	"  （那是删一大片）。插件会直接拒绝并告诉你该用哪个操作。\n" +
	"- **批量写入是部分成功的**：失败几条不会让整批回滚。出参里 `成功条数`/`失败条数`/`失败原因`\n" +
	"  都给了，**记得在流程里判失败条数**，别只看有没有报错。\n" +
	"- **分页最多翻到第 10000 条**（from + size 的硬上限）。要全量导出用重建索引，\n" +
	"  或用通用调用走 `search_after` / PIT。\n"
